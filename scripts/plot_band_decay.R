build_stack_plot <- function(entity_name, plot_data, relative, show_title, show_y_label, show_x_label, absolute_ylim) {
  entity <- band_data$entities[[entity_name]]
  years <- sort(unique(plot_data$year))
  marked <- masked_years(entity)
  value_column <- if (relative) "share" else "count"
  y_limit <- if (relative) 1 else absolute_ylim * 1.04
  if (y_limit <= 0) y_limit <- 1
  labels <- as.character(years)
  panel_labels <- labs(
    title = if (show_title) paste(if (relative) "Relative" else "Absolute", "abundance"),
    x = if (show_x_label) "Collection year",
    y = if (show_y_label) if (relative) "Share" else "Count"
  )

  if (length(years) == 0L) {
    return(
      ggplot() + annotate("text", x = 0.5, y = 0.5, label = "No data", color = "#555555") +
        xlim(0, 1) + ylim(0, 1) +
        panel_labels + base_plot_theme
    )
  }

  plot_data <- stack_bounds(plot_data, value_column)
  plot <- ggplot(plot_data, aes(x = year, ymin = ymin, ymax = ymax, fill = group, group = group)) +
    geom_ribbon(stat = "identity", color = "white", linewidth = 0.14, outline.type = "full") +
    scale_fill_manual(values = serotype_colors, limits = display_columns, drop = FALSE) +
    scale_x_continuous(breaks = years, labels = labels, limits = c(min(years) - 0.5, max(years) + 0.5), expand = c(0, 0)) +
    coord_cartesian(ylim = c(0, y_limit), expand = FALSE) +
    panel_labels + base_plot_theme

  if (relative) {
    plot <- plot + scale_y_continuous(breaks = seq(0, 1, by = 0.25), labels = function(values) paste0(round(values * 100), "%"))
  } else {
    plot <- plot + scale_y_continuous(
      breaks = pretty(c(0, y_limit), n = if (show_title) 5 else 2), labels = format_count
    )
    plot <- add_count_labels(plot, plot_data, y_limit)
  }

  for (year in marked) {
    plot <- plot + annotation_custom(
      year_hatch_grob(),
      xmin = year - 0.5, xmax = year + 0.5, ymin = 0, ymax = y_limit
    )
  }
  plot
}

build_decay_plot <- function(entity_name, show_title, show_y_label, show_x_label) {
  entity <- band_data$entities[[entity_name]]
  decay <- entity$decay
  observed <- data.frame(lag = as.numeric(decay$lag), similarity = as.numeric(decay$similarity))
  xmax <- max(1, observed$lag)
  title <- if (show_title) "Morisita-Horn decay" else NULL
  y_label <- if (show_y_label) "Similarity" else NULL
  plot <- ggplot(observed, aes(x = lag, y = similarity)) +
    geom_point(size = 1.8, alpha = 0.65, color = "#222222", stroke = 0) +
    scale_x_continuous(breaks = seq(0, xmax, by = max(1, floor(xmax / 5))), limits = c(0, xmax * 1.04), expand = c(0, 0)) +
    scale_y_continuous(breaks = if (show_title) seq(0, 1, by = 0.2) else c(0, 0.5, 1)) +
    labs(title = title, x = if (show_x_label) "Year lag" else NULL, y = y_label) +
    base_plot_theme +
    theme(axis.text.x = element_text(angle = 0, hjust = 0.5), panel.grid.major.x = element_line(color = "#f0f2f5", linewidth = 0.25))

  fit <- decay$fit
  if (is.null(fit)) {
    return(plot + coord_cartesian(ylim = c(0, 1.02)) + annotate(
      "text", x = xmax / 2, y = 0.5, label = "Not fit\n< 3 lag pairs", color = "#555555", size = BASE_TEXT_SIZE, size.unit = "pt"
    ))
  }
  fit_data <- data.frame(
    lag = fit$query, median = fit$median, lower = fit$lower, upper = fit$upper
  )
  upper_limit <- max(c(1.02, observed$similarity, fit_data$upper), na.rm = TRUE)
  lower_limit <- min(c(0, observed$similarity, fit_data$lower), na.rm = TRUE)
  plotted_upper <- upper_limit * 1.05
  # The export supplies normalized curves, but the table retains raw fit parameters.
  plot +
    geom_ribbon(
      data = fit_data, aes(x = lag, ymin = lower, ymax = upper), inherit.aes = FALSE,
      fill = "#4c78a8", alpha = 0.22, color = NA
    ) +
    geom_line(
      data = fit_data, aes(x = lag, y = median), inherit.aes = FALSE, color = "#1f4e79", linewidth = 0.7
    ) +
    coord_cartesian(ylim = c(lower_limit, plotted_upper))
}

# Legend and parameter table ---------------------------------------------------

make_legend_grob <- function(labels, colors, columns = 6L) {
  if (length(labels) == 0L) return(nullGrob())
  colors <- unname(colors[labels])
  columns <- min(columns, length(labels))
  rows <- ceiling(length(labels) / columns)
  legend <- gtable::gtable(
    widths = rep(unit.c(unit(0.32, "in"), unit(1, "null")), columns),
    heights = unit(c(0.42, rep(0.30, rows)), "in")
  )
  heading <- textGrob(
    "MLST-CPS types", x = 0, just = "left", gp = gpar(fontsize = HEADING_TEXT_SIZE, fontface = "bold", col = "#1e293b")
  )
  legend <- gtable::gtable_add_grob(legend, heading, t = 1, l = 1, b = 1, r = columns * 2)
  for (index in seq_along(labels)) {
    row <- (index - 1L) %% rows + 2L
    column <- ((index - 1L) %/% rows) * 2L + 1L
    swatch <- rectGrob(
      x = 0, just = "left", width = unit(0.22, "in"), height = unit(0.22, "in"),
      gp = gpar(fill = colors[index], col = NA)
    )
    label <- textGrob(labels[index], x = 0, just = "left", gp = gpar(fontsize = BASE_TEXT_SIZE, col = "#475569"))
    legend <- gtable::gtable_add_grob(legend, swatch, t = row, l = column, b = row, r = column)
    legend <- gtable::gtable_add_grob(legend, label, t = row, l = column + 1L, b = row, r = column + 1L)
  }
  legend
}

format_table_number <- function(value) {
  if (is.null(value) || length(value) == 0L || is.na(value)) "" else sprintf("%.2f", value)
}

make_parameter_table <- function() {
  include_sigma <- any(vapply(entity_order, function(name) !is.null(band_data$entities[[name]]$decay$fit$sigma), logical(1)))
  headers <- c("Country", "n", "y0", "b", "c")
  if (include_sigma) headers <- c(headers, "sigma")
  rows <- lapply(seq_along(entity_order), function(index) {
    entity_name <- entity_order[index]
    entity <- band_data$entities[[entity_name]]
    fit <- entity$decay$fit
    label <- if (index == 1L) entity_label(entity_name) else entity_name
    values <- c(
      label, format_count(entity$analysis_total),
      if (is.null(fit)) "not fit" else format_table_number(fit$y0),
      format_table_number(fit$b), format_table_number(fit$c)
    )
    if (include_sigma) values <- c(values, format_table_number(fit$sigma))
    values
  })
  rbind(headers, do.call(rbind, rows))
}

draw_parameter_table <- function(cells) {
  row_count <- nrow(cells)
  column_count <- ncol(cells)
  column_widths <- c(0.38, rep(0.62 / (column_count - 1L), column_count - 1L))
  column_edges <- c(0, cumsum(column_widths))
  for (row in seq_len(row_count)) {
    y <- 1 - (row - 0.5) / row_count
    grid.rect(
      y = y, height = 1 / row_count,
      gp = gpar(fill = if (row == 1L) "#eaf0f5" else if (row %% 2L == 0L) "#f7f9fb" else "white", col = NA)
    )
    for (column in seq_len(column_count)) {
      grid.text(
        cells[row, column],
        x = if (column == 1L) 0.02 else column_edges[column] + column_widths[column] / 2,
        y = y,
        just = if (column == 1L) "left" else "centre",
        gp = gpar(fontsize = BASE_TEXT_SIZE, col = "#475569", fontface = if (row == 1L) "bold" else "plain")
      )
    }
  }
}

