makeContent.year_hatch <- function(grob) {
  # Resolve physical spacing at draw time and align hatch strokes across panels.
  width <- convertWidth(unit(1, "npc"), "in", valueOnly = TRUE)
  height <- convertHeight(unit(1, "npc"), "in", valueOnly = TRUE)
  origin <- deviceLoc(unit(0, "npc"), unit(0, "npc"), valueOnly = TRUE)
  symbols <- strsplit(grob$hatch, "", fixed = TRUE)[[1]]
  strokes <- lapply(c(1, -1), function(direction) {
    repeats <- sum(symbols %in% c(if (direction == 1) "/" else "\\", "x", "X"))
    if (repeats == 0L) return(nullGrob())
    spacing <- 2 / (6 * repeats)
    phase <- (if (direction == 1) origin$x - origin$y else -origin$x - origin$y - width) %% spacing
    offsets <- seq(floor((-width - phase) / spacing), ceiling((height - phase) / spacing)) * spacing + phase
    x_start <- pmax(0, -offsets)
    x_end <- pmin(width, height - offsets)
    visible <- x_start < x_end
    segmentsGrob(
      x0 = unit(if (direction == 1) x_start[visible] else width - x_start[visible], "in"),
      x1 = unit(if (direction == 1) x_end[visible] else width - x_end[visible], "in"),
      y0 = unit((x_start + offsets)[visible], "in"),
      y1 = unit((x_end + offsets)[visible], "in"),
      gp = gpar(col = "#666666", alpha = grob$alpha, lwd = 4 / 3, lineend = "butt")
    )
  })
  setChildren(grob, do.call(gList, c(list(
    rectGrob(gp = gpar(fill = "#b0b0b0", col = NA, alpha = grob$alpha))
  ), strokes)))
}

