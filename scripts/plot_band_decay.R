add_count_labels <- function(plot, plot_data, y_limit) {
  if (length(unique(plot_data$year)) > plot_config$count_label_max_years) return(plot)
  totals <- aggregate(count ~ year, plot_data, sum)
  cutoff <- plot_config$count_label_max_y_fraction * y_limit
  labels_data <- totals[totals$count > 0 & totals$count <= cutoff, , drop = FALSE]
  labels_data$label <- format_count(labels_data$count)
  labels_data$y <- labels_data$count + 0.015 * y_limit
  plot + geom_text(
    data = labels_data, aes(x = year, y = y, label = label), inherit.aes = FALSE,
    size = BASE_TEXT_SIZE, size.unit = "pt", color = "#333333", vjust = 0
  )
}

