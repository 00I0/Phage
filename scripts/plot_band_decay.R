format_count <- function(values) {
  formatC(round(values), format = "d", big.mark = ",")
}

entity_label <- function(entity_name) {
  if (entity_name == "GLOBAL") "European aggregate" else entity_name
}

entity_frame <- function(entity_name) {
  entity <- band_data$entities[[entity_name]]
  years <- as.numeric(entity$display_years)
  data.frame(
    entity = rep(entity_name, length(years) * length(display_columns)),
    year = rep(years, times = length(display_columns)),
    group = factor(rep(display_columns, each = length(years)), levels = display_columns),
    count = as.numeric(unlist(entity$grouped_counts[display_columns], use.names = FALSE)),
    share = as.numeric(unlist(entity$grouped_proportions[display_columns], use.names = FALSE))
  )
}

masked_years <- function(entity) {
  sort(unique(c(as.numeric(entity$excluded_years), as.numeric(entity$missing_years))))
}

stack_bounds <- function(plot_data, value_column) {
  # Stack in exported serotype order, shared by the absolute and relative panels.
  plot_data$ymin <- 0
  plot_data$ymax <- 0
  for (year in unique(plot_data$year)) {
    indices <- which(plot_data$year == year)
    upper <- cumsum(plot_data[[value_column]][indices])
    plot_data$ymin[indices] <- c(0, head(upper, -1L))
    plot_data$ymax[indices] <- upper
  }
  plot_data
}

