#!/usr/bin/env Rscript

library(ggplot2)
library(grid)

# Configuration and exported data ----------------------------------------------

DATA_FILE <- "data/band_decay_data.R"
PALETTE_FILE <- "data/palette.R"
OUTPUT_FILE <- "plots_6/band_composition_90pct_cannonical.png"
OUTPUT_FORMATS <- c("png", "pdf")
USE_CANONICAL_SEROTYPE_ORDER <- TRUE
BASE_TEXT_SIZE <- 12
AXIS_TITLE_SIZE <- 14
COUNTRY_TEXT_SIZE <- 16

load_r_object <- function(data_file, object_name) {
  data_environment <- new.env(parent = baseenv())
  sys.source(data_file, envir = data_environment)
  data_environment[[object_name]]
}

# Both files are generated by update_fitted_country_curves_data.py.
curve_data <- load_r_object(DATA_FILE, "curve_data")
palette_data <- load_r_object(PALETTE_FILE, "palette_data")
band_data <- curve_data$band_decay
entity_order <- band_data$entity_order[band_data$entity_order != "GLOBAL"]
display_columns <- band_data$display_columns
if (USE_CANONICAL_SEROTYPE_ORDER) {
  canonical_order <- c(
    "ST147-KL64", "ST512-KL107", "ST307-KL102", "ST11-KL24",
    "ST101-KL17", "ST395-KL2", "ST395-KL64", "ST258-KL106",
    "ST147-KL107", "ST15-KL112", "ST39-KL23", "ST395-KL39",
    "ST15-KL24", "ST392-KL27", "ST383-KL30", "ST437-KL36"
  )
  top_to_bottom <- c(
    intersect(canonical_order, display_columns),
    setdiff(display_columns, c(canonical_order, "Other")),
    intersect("Other", display_columns)
  )
  display_columns <- rev(top_to_bottom)
}
plot_config <- band_data$plot
serotype_colors <- palette_data$serotype_colors[display_columns]


entity_frame <- function(entity_name) {
  entity <- band_data$entities[[entity_name]]
  years <- as.numeric(entity$display_years)
  data.frame(
    entity = rep(entity_name, length(years) * length(display_columns)),
    year = rep(years, times = length(display_columns)),
    group = factor(rep(display_columns, each = length(years)), levels = display_columns),
    share = as.numeric(unlist(entity$grouped_proportions[display_columns], use.names = FALSE))
  )
}

masked_years <- function(entity) {
  sort(unique(c(as.numeric(entity$excluded_years), as.numeric(entity$missing_years))))
}

stack_bounds <- function(plot_data, value_column) {
  plot_data$ymin <- 0
  plot_data$ymax <- 0
  for (year in unique(plot_data$year)) {
    indices <- which(plot_data$year == year)
    upper <- cumsum(plot_data[[value_column]][indices])
    plot_data$ymin[indices] <- c(0, head(upper, -1L))
    plot_data$ymax[indices] <- upper
  }
  plot_data
}

# Panel styling and overlays ---------------------------------------------------

year_hatch_grob <- function() {
  gTree(hatch = plot_config$excluded_year_hatch, alpha = plot_config$excluded_year_alpha, cl = "year_hatch")
}

makeContent.year_hatch <- function(grob) {
  # Resolve physical spacing at draw time and align hatch strokes across panels.
  width <- convertWidth(unit(1, "npc"), "in", valueOnly = TRUE)
  height <- convertHeight(unit(1, "npc"), "in", valueOnly = TRUE)
  origin <- deviceLoc(unit(0, "npc"), unit(0, "npc"), valueOnly = TRUE)
  symbols <- strsplit(grob$hatch, "", fixed = TRUE)[[1]]
  strokes <- lapply(c(1, -1), function(direction) {
    repeats <- sum(symbols %in% c(if (direction == 1) "/" else "\\", "x", "X"))
    if (repeats == 0L) return(nullGrob())
    spacing <- 2 / (6 * repeats)
    phase <- (if (direction == 1) origin$x - origin$y else -origin$x - origin$y - width) %% spacing
    offsets <- seq(floor((-width - phase) / spacing), ceiling((height - phase) / spacing)) * spacing + phase
    x_start <- pmax(0, -offsets)
    x_end <- pmin(width, height - offsets)
    visible <- x_start < x_end
    segmentsGrob(
      x0 = unit(if (direction == 1) x_start[visible] else width - x_start[visible], "in"),
      x1 = unit(if (direction == 1) x_end[visible] else width - x_end[visible], "in"),
      y0 = unit((x_start + offsets)[visible], "in"),
      y1 = unit((x_end + offsets)[visible], "in"),
      gp = gpar(col = "#666666", alpha = grob$alpha, lwd = 4 / 3, lineend = "butt")
    )
  })
  setChildren(grob, do.call(gList, c(list(
    rectGrob(gp = gpar(fill = "#b0b0b0", col = NA, alpha = grob$alpha))
  ), strokes)))
}

base_plot_theme <- theme_classic(base_size = BASE_TEXT_SIZE, base_family = "sans") +
  theme(
    panel.grid.minor = element_blank(),
    panel.grid.major = element_blank(),
    panel.grid.major.x = element_blank(),
    legend.position = "none",
    axis.title = element_text(color = "black", size = AXIS_TITLE_SIZE),
    axis.text = element_text(color = "black", size = BASE_TEXT_SIZE),
    axis.text.x = element_text(size = BASE_TEXT_SIZE, angle = 90, hjust = 1, vjust = 0.5, margin = margin(t = 4)),
    axis.line = element_line(color = "black", linewidth = 0.3),
    axis.ticks = element_line(color = "black", linewidth = 0.3),
    axis.ticks.length = unit(1.5, "mm"),
    plot.margin = margin(6, 10, 8 - (1.5 * 72.27 / 25.4 - 2), 6 - (1.5 * 72.27 / 25.4 - 2))
  )


build_stack_plot <- function(entity_name, plot_data, show_x_label) {
  entity <- band_data$entities[[entity_name]]
  years <- sort(unique(plot_data$year))
  panel_labels <- labs(x = if (show_x_label) "Year of isolation", y = NULL)
  y_scale <- scale_y_continuous(
    breaks = seq(0, 1, by = 0.25), labels = function(values) sprintf("%.2f", values)
  )

  if (length(years) == 0L) {
    return(
      ggplot() + annotate("text", x = 0.5, y = 0.5, label = "No data", color = "#555555") +
        xlim(0, 1) + y_scale + coord_cartesian(ylim = c(0, 1), expand = FALSE) +
        panel_labels + base_plot_theme
    )
  }

  plot_data <- stack_bounds(plot_data, "share")
  plot <- ggplot(plot_data, aes(x = year, ymin = ymin, ymax = ymax, fill = group, group = group)) +
    geom_ribbon(stat = "identity", color = "white", linewidth = 0.14, outline.type = "full") +
    scale_fill_manual(values = serotype_colors, limits = display_columns, drop = FALSE) +
    scale_x_continuous(
      breaks = years, labels = as.character(years),
      limits = c(min(years), max(years) + 0.5), expand = c(0, 0)
    ) +
    y_scale + coord_cartesian(ylim = c(0, 1), expand = FALSE) +
    panel_labels + base_plot_theme

  for (year in masked_years(entity)) {
    plot <- plot + annotation_custom(
      year_hatch_grob(), xmin = year - 0.5, xmax = year + 0.5, ymin = 0, ymax = 1
    )
  }
  plot
}



strike_axis_labels <- function(grob, years) {
  if (inherits(grob, "text")) {
    indices <- which(as.character(grob$label) %in% as.character(years))
    strokes <- lapply(indices, function(index) {
      label <- textGrob(grob$label[index], gp = grob$gp)
      width <- grobWidth(label)
      height <- grobHeight(label)
      segmentsGrob(
        x0 = unit(0.5, "npc") - grob$hjust * width,
        x1 = unit(0.5, "npc") + (1 - grob$hjust) * width,
        y0 = unit(0.5, "npc") + (0.5 - grob$vjust) * height,
        y1 = unit(0.5, "npc") + (0.5 - grob$vjust) * height,
        gp = gpar(col = "black", lwd = 1.5),
        vp = viewport(x = grob$x[index], y = grob$y[index], angle = grob$rot)
      )
    })
    return(gTree(children = do.call(gList, c(list(grob), strokes))))
  }
  if (!is.null(grob$children)) {
    grob$children <- do.call(gList, lapply(grob$children, strike_axis_labels, years = years))
  }
  if (!is.null(grob$grobs)) {
    grob$grobs <- lapply(grob$grobs, strike_axis_labels, years = years)
  }
  grob
}

build_plot_rows <- function(entity_frames) {
  lapply(seq_along(entity_order), function(index) {
    entity_name <- entity_order[index]
    plot <- ggplotGrob(build_stack_plot(
      entity_name, entity_frames[[index]], show_x_label = index == length(entity_order)
    ))
    if (isTRUE(plot_config$strike_excluded_year_labels)) {
      years <- masked_years(band_data$entities[[entity_name]])
      axis_index <- which(plot$layout$name == "axis-b")
      plot$grobs[[axis_index]] <- strike_axis_labels(plot$grobs[[axis_index]], years)
    }
    plot
  })
}

align_plot_rows <- function(plot_rows) {
  widths <- do.call(unit.pmax, lapply(plot_rows, function(plot) plot$widths))
  fixed_heights <- numeric(length(plot_rows))
  for (index in seq_along(plot_rows)) {
    plot_rows[[index]]$widths <- widths
    panel_row <- plot_rows[[index]]$layout$t[plot_rows[[index]]$layout$name == "panel"]
    fixed_heights[index] <- convertHeight(sum(plot_rows[[index]]$heights[-panel_row]), "in", valueOnly = TRUE)
  }
  list(plots = plot_rows, fixed_heights = fixed_heights)
}

draw_plot_rows <- function(plot_rows, panel_heights) {
  for (index in seq_along(entity_order)) {
    pushViewport(viewport(layout.pos.row = index, layout.pos.col = 2L, clip = "on"))
    grid.draw(plot_rows[[index]])
    upViewport()
    row_grob <- plot_rows[[index]]
    panel_row <- row_grob$layout$t[row_grob$layout$name == "panel"]
    label_y <- unit(1, "npc") - sum(row_grob$heights[seq_len(panel_row - 1L)]) - unit(panel_heights[index] / 2, "in")
    pushViewport(viewport(layout.pos.row = index, layout.pos.col = 1L))
    grid.text(
      entity_order[index], x = unit(1, "npc") - unit(0.17, "in"), y = label_y, rot = 90,
      gp = gpar(fontsize = COUNTRY_TEXT_SIZE, fontfamily = "sans", fontface = "bold", col = "black")
    )
    upViewport()
  }
}

render_band_composition <- function(output_file) {
  output_format <- tolower(tools::file_ext(output_file))
  if (!output_format %in% c("png", "pdf")) {
    stop("Output file must have a .png or .pdf extension.")
  }
  entity_frames <- lapply(entity_order, entity_frame)
  figure_width <- 9
  figure_height <- max(10, 2.1 * length(entity_order) + 0.5)

  output_directory <- dirname(output_file)
  if (!dir.exists(output_directory)) dir.create(output_directory, recursive = TRUE)
  if (output_format == "pdf") {
    grDevices::pdf(
      output_file, width = figure_width, height = figure_height,
      paper = "special", bg = "white", colormodel = "srgb",
      version = "1.4", useDingbats = FALSE
    )
  } else {
    ragg::agg_png(output_file, width = figure_width, height = figure_height, units = "in", res = 300, background = "white")
  }
  on.exit(dev.off())

  grid.newpage()
  aligned <- align_plot_rows(build_plot_rows(entity_frames))
  panel_ratios <- rep(1, length(entity_order))
  available_height <- figure_height - 0.5 - sum(aligned$fixed_heights)
  panel_heights <- available_height * panel_ratios / sum(panel_ratios)
  layout <- grid.layout(
    nrow = length(entity_order),
    ncol = 2L,
    widths = unit.c(unit(0.4, "in"), unit(1, "null")),
    heights = unit(aligned$fixed_heights + panel_heights, "in")
  )
  pushViewport(viewport(width = unit(figure_width - 0.5, "in"), height = unit(figure_height - 0.5, "in"), layout = layout))
  draw_plot_rows(aligned$plots, panel_heights)
  upViewport()
}

for (output_format in unique(OUTPUT_FORMATS)) {
  output_file <- paste0(tools::file_path_sans_ext(OUTPUT_FILE), ".", output_format)
  render_band_composition(output_file)
  cat(sprintf("Wrote %s\n", output_file))
}
